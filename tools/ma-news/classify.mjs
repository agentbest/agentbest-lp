// tools/ma-news/classify.mjs … 適時開示のタイトルから「M&Aニュースとして出すか」を決める
//
// TDnetには1日200〜400件の開示が流れてくる。そのうち記事にする価値があるのは数件で、
// ふるいの目が粗いと「譲渡制限付株式報酬」「自己株式の取得」まで拾ってしまう。
// 判定はタイトルだけで完結させる（PDFを開くのは通過したものだけ。無駄なDLを減らす）。

/** 取引の型。記事のタグと本文テンプレの分岐に使う */
export const DEAL_TYPES = [
  { key: 'tob',       label: '公開買付け（TOB）', re: /公開買[付附]/ },
  { key: 'exchange',  label: '株式交換・株式交付', re: /株式交[換付]/ },
  { key: 'merger',    label: '合併',             re: /合[併并]/ },
  { key: 'split',     label: '会社分割',         re: /(会社分割|吸収分割|新設分割)/ },
  { key: 'transfer',  label: '事業譲渡・譲受',   re: /事業(の)?(譲渡|譲受|承継)/ },
  { key: 'sell',      label: '子会社・持分の譲渡', re: /(株式|持分|全株式)(の)?譲渡|譲渡(に|を)/ },
  { key: 'buy',       label: '子会社化・株式取得', re: /(子会社化|株式(の)?取得|グループ会社化|持分法適用関連会社)/ },
  { key: 'alliance',  label: '資本業務提携',     re: /資本(業務)?提携/ },
];

// これが入っていたら、たとえ「取得」「譲渡」の字があってもM&Aではない
const NOISE = [
  /自己株式/,                       // 自社株買い
  /譲渡制限(付)?株式|株式報酬|ストック・?オプション|新株予約権/, // 役員報酬まわり
  /株式(分割|併合|無償割当)/,
  /単元株式数/,
  /(株主|名義書換|基準日)の?設定?$/,
  /投資(法人|口)の|不動産(信託受益権)?の(取得|譲渡)/, // REITの物件売買はM&Aではない
  /有価証券報告書|四半期報告書|決算(短信|説明)/,
  /配当|株主優待/,
  /固定資産(の)?(譲渡|取得)/,               // 不動産・設備の売買
  /(展開権|営業権|商標権|特許権|債権|優先交渉権)(の)?(譲渡|取得)/,
  /資金の借入|借入(れ)?(実行)?に関する/,    // 買収資金の調達開示。案件そのものは別に出る
  /(増資|新株式発行|第三者割当).*(のみ)?に関するお知らせ$/,
  /訂正/,                                   // 訂正開示。第一報を出していれば足りる
  /条件の変更|期間の(延長|変更)/,           // 進行中の案件の条件変更。第一報ではない
  /応募|意見表明|賛同/,                     // 他社のTOBへの応募・意見表明。自社の取引ではない
  /合意解約|中止|白紙/,
  /貸倒引当金|評価減|特別損失|損害賠償/,
];

// グループ内の器いじり。開示は出るがニュースにはならない
const INTERNAL = [
  /連結子会社間/,
  /当社(の)?(完全)?子会社間/,
  /(子会社|孫会社|グループ会社)(株式)?の(吸収)?合併/,
  /(連結子会社|完全子会社)による(孫会社|子会社)/,
  /(子会社|孫会社)間の/,
  /完全子会社との(会社分割|吸収分割|合併)/,
  /簡易(合併|吸収分割)?.*(子会社|グループ)/,
  /組織再編.*(子会社間|グループ内)/,
  /商号変更(のみ)?に関する/,
];

// 続報。第一報を出していないと文脈が通らないので既定では出さない
const FOLLOWUP = [
  /開示事項の(経過|変更|中止|延期)/,
  /^（?経過開示）?/,
  /の経過に関する/,
  /に関する(お知らせ)?の(一部)?訂正/,
  /訂正(および|及び)/,
];

/**
 * @returns {{ok:boolean, reason?:string, type?:string, typeLabel?:string, followup?:boolean}}
 */
export function classify(title) {
  const t = String(title || '').replace(/\s+/g, '');

  for (const re of NOISE) if (re.test(t)) return { ok: false, reason: 'ノイズ（M&Aではない）' };

  const hit = DEAL_TYPES.find((d) => d.re.test(t));
  if (!hit) return { ok: false, reason: 'M&Aの語が無い' };

  for (const re of INTERNAL) if (re.test(t)) return { ok: false, reason: 'グループ内再編' };

  const followup = FOLLOWUP.some((re) => re.test(t));
  return { ok: true, type: hit.key, typeLabel: hit.label, followup };
}
